from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ChatMessage(BaseModel):
    """ ChatMessage Schema """
    role: str = Field(..., description="Role of the message sender: 'user', 'assistant', or 'system'")
    content: str = Field(..., description="The message content")


class ChatRequest(BaseModel):
    """ ChatRequest Schema """
    messages: List[ChatMessage] = Field(..., description="Full conversation history")
    workspace: Optional[str] = Field(None, description="Optional custom workspace path override")


class ChatResponse(BaseModel):
    """ ChatResponse Schema """
    response: str = Field(..., description="Assistant reply generated by the agent")
    status: str = Field("success", description="Execution status")


class HealthResponse(BaseModel):
    """ HealthResponse Schema """
    status: str = "ok"
    version: str = "0.1.0"